// Moves/alters the camera positions based on user input
void DoMovement()
{

	// Camera controls
	if (keys[GLFW_KEY_W] || keys[GLFW_KEY_UP])
	{
		camera.ProcessKeyboard(FORWARD, deltaTime);

	}

	if (keys[GLFW_KEY_S] || keys[GLFW_KEY_DOWN])
	{
		camera.ProcessKeyboard(BACKWARD, deltaTime);


	}

	if (keys[GLFW_KEY_A] || keys[GLFW_KEY_LEFT])
	{
		camera.ProcessKeyboard(LEFT, deltaTime);


	}

	if (keys[GLFW_KEY_D] || keys[GLFW_KEY_RIGHT])
	{
		camera.ProcessKeyboard(RIGHT, deltaTime);


	}

	if (keys[GLFW_KEY_T])
	{
		pointLightPositions[0].x += 0.01f;
	}
	if (keys[GLFW_KEY_G])
	{
		pointLightPositions[0].x -= 0.01f;
	}

	if (keys[GLFW_KEY_Y])
	{
		pointLightPositions[0].y += 0.01f;
	}

	if (keys[GLFW_KEY_H])
	{
		pointLightPositions[0].y -= 0.01f;
	}
	if (keys[GLFW_KEY_U])
	{
		pointLightPositions[0].z -= 0.1f;
	}
	if (keys[GLFW_KEY_J])
	{
		pointLightPositions[0].z += 0.01f;
	}

}

// Is called whenever a key is pressed/released via GLFW
void KeyCallback(GLFWwindow* window, int key, int scancode, int action, int mode)
{
	if (GLFW_KEY_ESCAPE == key && GLFW_PRESS == action)
	{
		glfwSetWindowShouldClose(window, GL_TRUE);
	}

	if (key >= 0 && key < 1024)
	{
		if (action == GLFW_PRESS)
		{
			keys[key] = true;
		}
		else if (action == GLFW_RELEASE)
		{
			keys[key] = false;
		}
	}

	if (keys[GLFW_KEY_SPACE])
	{
		active = !active;
		if (active)
		{
			Light1 = glm::vec3(1.0f, 1.0f, 0.0f);

		}
		else
		{
			Light1 = glm::vec3(0);//Cuado es solo un valor en los 3 vectores pueden dejar solo una componente
		}
	}
	if (key == GLFW_KEY_N && action == GLFW_PRESS)
	{
		AnimBall = !AnimBall;

	}
}
void Animation() {
	if (AnimBall)
	{
		// Detecta la cercania entre el perro y la pelota antes de avanzar
		float xDog = radioTrayectoria * cos(rotDog);
		float zDog = radioTrayectoria * sin(rotDog);
		float xBall = radioTrayectoria * cos(rotBall);
		float zBall = radioTrayectoria * sin(rotBall);
		float distancia = sqrt((xDog - xBall) * (xDog - xBall) + (zDog - zBall) * (zDog - zBall));

		// Prepara el cabezazo antes de que la pelota alcance el cuerpo del perro
		if (distancia < 0.46f && !enContacto && !golpeando && alturaRebote <= 0.0f)
		{
			// El modelo original del perro mira hacia el eje Z positivo.
			// atan2 permite que la nariz apunte a la pelota, no la cola.
			float haciaPelotaX = xBall - xDog;
			float haciaPelotaZ = zBall - zDog;
			orientacionGolpeDog = atan2(haciaPelotaX, haciaPelotaZ);

			golpeando = true;
			pelotaGolpeada = false;
			tiempoGolpe = 0.0f;
			enContacto = true;
		}

		// Animacion del golpe: preparacion, impulso y recuperacion
		cabeceoDog = 0.0f;
		elevacionDog = 0.0f;
		avanceDog = 0.0f;

		if (golpeando)
		{
			// Durante un instante, ambos frenan para que el golpe sea visible
			tiempoGolpe += deltaTime;
			const float PI = 3.14159265f;

			if (tiempoGolpe < 0.10f)
			{
				// El perro baja el hocico antes del golpe
				float fase = tiempoGolpe / 0.10f;
				cabeceoDog = 12.0f * sin(PI * fase);
				elevacionDog = -0.04f * sin(PI * fase);
			}
			else if (tiempoGolpe < 0.28f)
			{
				// El perro impulsa el hocico hacia arriba y adelante
				float fase = (tiempoGolpe - 0.10f) / 0.18f;
				cabeceoDog = -28.0f * sin(PI * fase);
				elevacionDog = 0.15f * sin(PI * fase);
				avanceDog = 0.27f * sin(PI * fase);
			}

			if (tiempoGolpe >= 0.20f && !pelotaGolpeada)
			{
				// La pelota sale hacia arriba justo durante el cabezazo
				velocidadRebote = 5.8f;
				pelotaGolpeada = true;
			}

			if (tiempoGolpe >= 0.38f)
			{
				golpeando = false;
				tiempoGolpe = 0.0f;
			}
		}
		else
		{
			// Ambos siguen el mismo circulo, pero en sentidos contrarios
			rotDog += velocidadDog * deltaTime;  // Horario visto desde arriba
			rotBall -= velocidadBall * deltaTime; // Antihorario visto desde arriba

			// Evita que los angulos crezcan indefinidamente
			if (rotDog > 3.14159265f) rotDog -= 6.28318530f;
			if (rotBall < -3.14159265f) rotBall += 6.28318530f;
		}

		// La pelota sube y baja de forma mas visible mientras gira
		// Al encontrarse con el perro, vuelve a la altura del cabezazo
		float fasePelota = sin(rotDog - rotBall);
		posBall = alturaNariz + 2.6f * fasePelota * fasePelota;

		// Evita repetir el golpe mientras los modelos siguen juntos
		if (!golpeando)
		{
			xDog = radioTrayectoria * cos(rotDog);
			zDog = radioTrayectoria * sin(rotDog);
			xBall = radioTrayectoria * cos(rotBall);
			zBall = radioTrayectoria * sin(rotBall);
			distancia = sqrt((xDog - xBall) * (xDog - xBall) + (zDog - zBall) * (zDog - zBall));
			if (distancia > 0.60f) enContacto = false;
		}

		// Rebote de la pelota con gravedad
		if (velocidadRebote != 0.0f || alturaRebote > 0.0f)
		{
			alturaRebote += velocidadRebote * deltaTime;
			velocidadRebote -= 9.8f * deltaTime;
			if (alturaRebote <= 0.0f)
			{
				alturaRebote = 0.0f;
				velocidadRebote = 0.0f;
			}
		}
	}

	// Posiciones usadas para dibujar los modelos
	// Movimiento ligero del cuerpo para simular los pasos del perro
	float pasoDog = golpeando ? 0.0f : 0.025f * fabs(sin(rotDog * 12.0f));
	posicionDog = glm::vec3(radioTrayectoria * cos(rotDog), pasoDog,
		radioTrayectoria * sin(rotDog));
	posicionBall = glm::vec3(radioTrayectoria * cos(rotBall), posBall + alturaRebote,
		radioTrayectoria * sin(rotBall));
}

void MouseCallback(GLFWwindow* window, double xPos, double yPos)
{
	if (firstMouse)
	{
		lastX = xPos;
		lastY = yPos;
		firstMouse = false;
	}

	GLfloat xOffset = xPos - lastX;
	GLfloat yOffset = lastY - yPos;  // Reversed since y-coordinates go from bottom to left

	lastX = xPos;
	lastY = yPos;

	camera.ProcessMouseMovement(xOffset, yOffset);
}